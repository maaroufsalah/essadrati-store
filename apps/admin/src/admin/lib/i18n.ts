const DICTIONARIES = { fr, en } as const;
type Language = keyof typeof DICTIONARIES;

export function currentLanguage(): Language {
  let stored: string | null = null;
  try {
    stored = window.localStorage.getItem("lng");
  } catch {
    stored = null;
  }
  const language = (stored ?? navigator.language).slice(0, 2);
  return language === "en" ? "en" : "fr";
}

/** Translates a key, replacing {placeholders}. Unknown keys return the key itself. */
export function translate(key: string, values: Record<string, string | number> = {}): string {
  const language = currentLanguage();
  const dictionary: Partial<Record<string, string>> = DICTIONARIES[language];
  const reference: Partial<Record<string, string>> = fr;
  const template = dictionary[key] ?? reference[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
}

export function t(key: MessageKey, values?: Record<string, string | number>): string {
  return translate(key, values);
}

/** Message for a validation code from @nocido/types (e.g. "phone.invalid"). */
export function errorMessage(code: string | undefined): string {
  if (!code) return t("error.invalid");
  const translated = translate(`error.${code}`);
  return translated === `error.${code}` ? code : translated;
}

export function localeLabel(locale: string): string {
  return translate(`locale.${locale}`);
}
